function fill(id, nodes) {
  const root = document.getElementById(id);
  if (!root) return;
  root.innerHTML = '';
  nodes.forEach(node => root.appendChild(node));
}

async function fetchTariffs() {
  state.tariffs = FALLBACK_TARIFFS;
  try {
    const res = await fetch('/api/tariffs');
    if (!res.ok) throw new Error('api_error');
    const json = await res.json();
    state.tariffs = Array.isArray(json.tariffs) && json.tariffs.length ? json.tariffs : FALLBACK_TARIFFS;
  } catch (error) {
    state.tariffs = FALLBACK_TARIFFS;
  }
  renderPricing();
}


function localizeTariff(tariff) {
  const local = (TARIFF_I18N[state.lang] && TARIFF_I18N[state.lang][tariff.id]) || {};
  return { ...tariff, ...local };
}

function renderPricing() {
  const root = document.getElementById('pricingGrid');
  const planSelect = document.getElementById('planSelect');
  if (!root) return;
  root.innerHTML = '';
  if (planSelect) planSelect.innerHTML = '';
  state.tariffs.map(localizeTariff).forEach(tariff => {
    const buttonClass = tariff.highlighted ? 'primary-btn' : 'ghost-btn';
    const el = card(`pricing-card reveal ${tariff.highlighted ? 'highlighted' : ''}`, `
      <span class="pricing-badge">${escapeHtml(tariff.badge || '7 дней бесплатно')}</span>
      <h3>${escapeHtml(tariff.name)}</h3>
      <div class="price"><strong>${escapeHtml(tariff.price)}</strong><span>${escapeHtml(tariff.period || '')}</span></div>
      <p>${escapeHtml(tariff.description || '')}</p>
      <ul>${(tariff.features || []).map(item => `<li>${escapeHtml(item)}</li>`).join('')}</ul>
      <a class="${buttonClass}" href="#lead" data-plan="${escapeHtml(tariff.name)}">${tr('nav.cta')}</a>
    `);
    root.appendChild(el);
    if (planSelect) {
      const opt = document.createElement('option');
      opt.value = tariff.name;
      opt.textContent = `${tariff.name} — ${tariff.price}`;
      planSelect.appendChild(opt);
    }
  });
  root.querySelectorAll('[data-plan]').forEach(a => a.addEventListener('click', () => {
    if (planSelect) planSelect.value = a.dataset.plan;
  }));
  observeReveal();
}

function renderScenarios() {
  const data = activeCopy().scenarios;
  const tabs = document.getElementById('scenarioTabs');
  if (!tabs) return;
  tabs.innerHTML = '';
  Object.entries(data).forEach(([key, scenario]) => {
    const btn = document.createElement('button');
    btn.className = `scenario-tab ${key === state.scenario ? 'active' : ''}`;
    btn.textContent = scenario.tab;
    btn.addEventListener('click', () => {
      state.scenario = key;
      renderScenarios();
    });
    tabs.appendChild(btn);
  });
  renderScenarioContent();
}

function clearChatTimers() {
  state.chatTimers.forEach(timer => clearTimeout(timer));
  state.chatTimers = [];
}

function schedule(fn, delay) {
  const timer = setTimeout(fn, delay);
  state.chatTimers.push(timer);
  return timer;
}

function addTypingBubble(chat, type) {
  const bubble = card(`message ${type} typing`, `<small>${type === 'ai' ? 'VENSO' : tr('hero.card1Label')}</small><span class="typing-dots"><i></i><i></i><i></i></span>`);
  chat.appendChild(bubble);
  chat.scrollTop = chat.scrollHeight;
  return bubble;
}

function typeInto(element, text, speed = 18) {
  const target = document.createElement('span');
  target.className = 'typed-text';
  element.appendChild(target);
  let i = 0;
  function tick() {
    target.textContent = text.slice(0, i);
    i += 1;
    if (i <= text.length) schedule(tick, speed + Math.random() * 10);
  }
  tick();
}

function renderScenarioContent() {
  clearChatTimers();
  const scenario = activeCopy().scenarios[state.scenario] || activeCopy().scenarios.flowers;
  document.getElementById('scenarioTitle').textContent = scenario.title;
  const chat = document.getElementById('chatStream');
  chat.innerHTML = '';
  let delay = 250;
  scenario.messages.forEach(([type, text]) => {
    schedule(() => {
      const typing = addTypingBubble(chat, type);
      schedule(() => {
        typing.classList.remove('typing');
        typing.innerHTML = `<small>${type === 'ai' ? 'VENSO' : tr('hero.card1Label')}</small>`;
        typeInto(typing, escapeHtml(text), 12);
        chat.scrollTop = chat.scrollHeight;
      }, type === 'ai' ? 650 : 380);
    }, delay);
    delay += Math.min(2400, 900 + text.length * 24);
  });
  const recRoot = document.getElementById('recommendations');
  recRoot.innerHTML = '';
  scenario.recs.forEach(([icon, title, text, price], index) => {
    const rec = card(`rec-card ${index === 1 ? 'highlight' : ''}`, `<div><div class="rec-icon">${icon}</div><h3>${title}</h3><p>${text}</p></div><strong>${price}</strong>`);
    rec.style.animationDelay = `${index * 120}ms`;
    recRoot.appendChild(rec);
  });
  const stack = document.getElementById('automationStack');
  stack.innerHTML = '';
  scenario.stack.forEach(([title, text], index) => {
    const item = card('auto-item', `<div class="check">✓</div><div><strong>${title}</strong><span>${text}</span></div>`);
    item.style.animationDelay = `${index * 110}ms`;
    stack.appendChild(item);
  });
}

