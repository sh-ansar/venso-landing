function tr(path) {
  const parts = path.split('.');
  let current = t[state.lang] || t.ru;
  for (const part of parts) current = current && current[part];
  return current || path;
}

function activeCopy() {
  return copy[state.lang] || copy.ru;
}

function setLang(lang) {
  state.lang = lang;
  localStorage.setItem('venso_lang', lang);
  document.documentElement.lang = lang;
  document.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = tr(el.dataset.i18n); });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => { el.setAttribute('placeholder', tr(el.dataset.i18nPlaceholder)); });
  document.querySelectorAll('.lang-btn').forEach(btn => btn.classList.toggle('active', btn.dataset.lang === lang));
  renderStaticSections();
  renderScenarios();
  renderPricing();
}

function card(className, html) {
  const div = document.createElement('div');
  div.className = className;
  div.innerHTML = html;
  return div;
}

